def normalize_lang(value: str | None) -> str:
    raw = (value or "").strip().lower()
    if raw.startswith("fa"):
        return "fa"
    return "en"


def translate(lang: str, key: str, **kwargs: Any) -> str:
    bundle = STRINGS.get(normalize_lang(lang)) or STRINGS["en"]
    text = bundle.get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def nav_for(lang: str) -> list[tuple[str, str, str]]:
    t = lambda k: translate(lang, k)
    return [(key, t(label_key), href) for key, label_key, href in NAV_KEYS]


def service_columns_for(lang: str) -> list[tuple[str, str]]:
    t = lambda k: translate(lang, k)
    return [(key, t(label_key)) for key, label_key in SERVICE_COLUMN_KEYS]
